import jsPDF from 'jspdf';
import { Scheme } from './schemeRules';

export interface FormSubmissionData {
  scheme: Scheme;
  fullName: string;
  phone: string;
  aadhaarLast4: string;
  location: string;
  occupation: string;
  bankAccountLast4: string;
  upiId: string;
  appliedDate: string;
  applicationId: string;
  isSimulation: boolean;
}

/**
 * High-fidelity, multi-lingual PDF generator for Indian languages.
 * Instead of relying on ASCII-only Helvetica (which corrupts Kannada, Devanagari, and Tamil into '???'),
 * this uses an off-screen high-resolution HTML5 canvas rendering pipeline with the system's native
 * Unicode fonts (Nirmala UI / Arial Unicode MS / Noto Sans) to render genuine Indian scripts cleanly.
 */
export async function generateApplicationPDF(data: FormSubmissionData): Promise<void> {
  const canvas = document.createElement('canvas');
  // High-DPI A4 representation (approx 300 DPI: 2480 x 3508 pixels)
  const scale = 2;
  const width = 800 * scale;
  const height = 1130 * scale;
  canvas.width = width;
  canvas.height = height;

  const ctx = canvas.getContext('2d');
  if (!ctx) {
    console.error('Canvas 2D context not available for PDF export');
    return;
  }

  ctx.scale(scale, scale);

  // Background
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, 800, 1130);

  // Top Saffron Banner
  ctx.fillStyle = '#FF671F';
  ctx.fillRect(0, 0, 800, 85);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 22px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.textAlign = 'center';
  ctx.fillText('KAVACH VAANI (कवच वाणी) - CITIZEN WELFARE RECORD', 400, 42);

  ctx.font = '12px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText('Direct Voice-Assisted Welfare Application & Anti-Extortion Legal Slip', 400, 65);

  // Green Border Underline
  ctx.fillStyle = '#046A38';
  ctx.fillRect(0, 85, 800, 10);

  // Prototype Disclaimer Watermark Bar
  ctx.fillStyle = '#FEF3C7'; // Amber alert box
  ctx.strokeStyle = '#F59E0B';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.roundRect(40, 110, 720, 42, 8);
  ctx.fill();
  ctx.stroke();

  ctx.fillStyle = '#92400E';
  ctx.font = 'bold 11px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.textAlign = 'left';
  ctx.fillText('⚠️ HACKATHON PROTOTYPE SIMULATION NOTICE:', 55, 128);
  ctx.font = '10px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText('This document is generated by the Kavach Vaani Build for Bharat demo prototype. Application reference is a simulated demo reference.', 55, 142);

  // Metadata Box
  ctx.fillStyle = '#1E293B';
  ctx.font = 'bold 14px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(`Application Reference: ${data.applicationId} (Demo Sandbox)`, 40, 180);

  ctx.font = 'normal 12px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillStyle = '#475569';
  ctx.fillText(`Date & Timestamp: ${data.appliedDate}`, 40, 202);
  ctx.fillText('Channel: Kavach Vaani Voice Portal (Direct Citizen Self-Service)', 40, 222);

  // Entitlement Highlight Card
  ctx.fillStyle = '#FFF7ED';
  ctx.strokeStyle = '#FF671F';
  ctx.lineWidth = 1.5;
  ctx.beginPath();
  ctx.roundRect(40, 245, 720, 100, 10);
  ctx.fill();
  ctx.stroke();

  ctx.fillStyle = '#C2410C';
  ctx.font = 'bold 16px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(`${data.scheme.name} | ${data.scheme.nameNative}`, 60, 275);

  ctx.fillStyle = '#046A38';
  ctx.font = 'bold 14px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(`Entitlement: ${data.scheme.benefitAmount}`, 60, 302);

  ctx.fillStyle = '#334155';
  ctx.font = 'normal 11px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(data.scheme.benefitDescription, 60, 325);

  // Applicant Profile Heading
  ctx.fillStyle = '#0F172A';
  ctx.font = 'bold 15px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText('Applicant Profile (Direct Voice Verified):', 40, 380);

  // Horizontal separator line
  ctx.strokeStyle = '#E2E8F0';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(40, 390);
  ctx.lineTo(760, 390);
  ctx.stroke();

  // Profile rows
  const profileFields = [
    ['Citizen Name:', data.fullName || 'Verified Citizen Applicant'],
    ['Contact Number:', data.phone ? `+91 ${data.phone}` : '+91 9876543210'],
    ['Aadhaar Number:', data.aadhaarLast4 ? `XXXX-XXXX-${data.aadhaarLast4} (Masked / Voice Verified)` : 'XXXX-XXXX-8921 (Voice Verified)'],
    ['Location / Work City:', data.location || 'Bengaluru, Karnataka'],
    ['Vocation / Trade Category:', data.occupation || data.scheme.category],
    ['Bank Account (DBT):', data.bankAccountLast4 ? `XXXX-XXXX-${data.bankAccountLast4} (Direct Benefit Transfer Active)` : 'XXXX-XXXX-6182 (PM-JanDhan Linked)'],
    ['Direct UPI ID:', data.upiId || 'Direct DBT Mode Active']
  ];

  let currentY = 420;
  profileFields.forEach(([label, val]) => {
    ctx.fillStyle = '#64748B';
    ctx.font = 'bold 12px "Nirmala UI", "Segoe UI", sans-serif';
    ctx.fillText(label, 60, currentY);

    ctx.fillStyle = '#0F172A';
    ctx.font = 'normal 12px "Nirmala UI", "Segoe UI", sans-serif';
    ctx.fillText(val, 260, currentY);

    currentY += 28;
  });

  // Statutory Rights Notice Card
  const rightsY = 650;
  ctx.fillStyle = '#F0FDF4';
  ctx.strokeStyle = '#22C55E';
  ctx.lineWidth = 1.2;
  ctx.beginPath();
  ctx.roundRect(40, rightsY, 720, 160, 10);
  ctx.fill();
  ctx.stroke();

  ctx.fillStyle = '#166534';
  ctx.font = 'bold 13px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText('🛡️ STATUTORY LEGAL RIGHTS & ANTI-EXTORTION NOTICE', 60, rightsY + 30);

  ctx.fillStyle = '#334155';
  ctx.font = 'bold 11px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(`Governing Act: ${data.scheme.protectionAct}`, 60, rightsY + 55);

  ctx.font = 'normal 11px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText('As per statutory provisions, no officer, agent, or local authority may demand commissions or unlawfully evict', 60, rightsY + 75);
  ctx.fillText('the applicant without required notices and committee approvals. No fee is required for this filing.', 60, rightsY + 95);

  ctx.fillStyle = '#B91C1C';
  ctx.font = 'bold 12px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.fillText(`Official Anti-Corruption & Grievance Helpline: ${data.scheme.grievanceHelpline}`, 60, rightsY + 130);

  // Bottom Footer
  ctx.fillStyle = '#94A3B8';
  ctx.font = 'italic 10px "Nirmala UI", "Segoe UI", sans-serif';
  ctx.textAlign = 'center';
  ctx.fillText('Kavach Vaani | Build for Bharat Initiative | Voice-Native Welfare Access Prototype', 400, 1080);

  // Convert rendered canvas to PDF image
  const imgData = canvas.toDataURL('image/png', 0.95);
  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  pdf.addImage(imgData, 'PNG', 0, 0, 210, 297);
  pdf.save(`Kavach-Vaani-${data.scheme.id}-${data.applicationId}.pdf`);
}
